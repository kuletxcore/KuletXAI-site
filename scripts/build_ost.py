"""Fetch each story's public IsekaiZero OST playlist and write src/data/ost.ts.

Run: python3 scripts/build_ost.py
Tracks stream from IsekaiZero's CDN (too large to host: ~135 min of audio).
"""
import json
import os
import urllib.request

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = 'https://api-us.isekaizero.ai/api/music'
REF = '?referralCode=95OBGFQX'

PLAYLISTS = {
    'acolytes': '6aabeb8f95bcb6ce01b95f15',
    'colossus-protocol': '6ac29251d57e12638cd45b18',
    'queen-bee': '6a9f0a6252e021ab1dc94311',
    'i-am-the-table': '6aa21d2ceb8350fd122c2706',
}


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'kuletx-site-builder'})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())


out = {}
for slug, pid in PLAYLISTS.items():
    d = fetch(f'{API}/playlists/{pid}?pageSize=500')['data']
    p = d['playlist']
    tracks = []
    for t in d['tracks']:
        t = t.get('track', t)
        m = t.get('media') or {}
        if t.get('explicit') or t.get('nsfw') or t.get('flagged') or t.get('visibility') != 'public' or not m.get('url'):
            continue
        tracks.append({
            'id': t['_id'],
            'title': t['songTitle'],
            'src': m['url'],
            'duration': round(m.get('duration') or 0),
            'image': t.get('imageUrl'),
            'url': f"https://www.isekaizero.ai/music/track/{t['_id']}{REF}",
            'instrumental': bool(t.get('isInstrumental')),
        })
    out[slug] = {
        'title': p['title'],
        'url': f'https://www.isekaizero.ai/music/playlist/{pid}{REF}',
        'image': p.get('imageUrl'),
        'tracks': tracks,
    }
    print(slug, len(tracks), 'tracks')

with open(os.path.join(SITE, 'src', 'data', 'ost.ts'), 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/build_ost.py from public IsekaiZero playlists.\n')
    f.write('export type OstTrack = { id: string; title: string; src: string; duration: number; image?: string; url: string; instrumental: boolean }\n')
    f.write('export type Ost = { title: string; url: string; image?: string; tracks: OstTrack[] }\n\n')
    f.write('export const OSTS: Record<string, Ost> = ')
    f.write(json.dumps(out, indent=2, ensure_ascii=False))
    f.write('\n')
